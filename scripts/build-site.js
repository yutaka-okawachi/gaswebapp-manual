const fs = require('fs');
const path = require('path');
const { root, sha256, normalizeText, writeIfChanged } = require('./sync/core');
function build(options = {}) {
    const languages = require('./site-languages');
    const bilingual = require('./sync/bilingual');
    const englishEnabled = bilingual.englishEnabled();
    let targetAliases;
    if (englishEnabled) {
        if (options.bilingualSource) targetAliases = languages.buildTargetAliases(options.bilingualSource);
        else {
            // A clean CI checkout rebuilds from the already published navigation mapping,
            // without requiring or publishing an authenticated source snapshot.
            const match = fs.readFileSync(path.join(root, 'index.html'), 'utf8').match(/window\.__SITE_LANGUAGE_NAV__=(\{[^]*?\});<\/script>/);
            if (match) targetAliases = JSON.parse(match[1]).targetAliases;
            if (!targetAliases) {
                const cached = JSON.parse(fs.readFileSync(path.join(root, '.sync-state/english/snapshot.json'), 'utf8'));
                targetAliases = languages.buildTargetAliases(bilingual.validateEnglishSource(cached));
            }
        }
    }
    if (englishEnabled) writeIfChanged('mahler-search-app/js/site-language-switch.js', languages.runtimeSource());
    const sources = JSON.parse(fs.readFileSync(path.join(root, 'frontend/bundle.json'), 'utf8'));
    const bundle = '// Generated by scripts/build-site.js. Edit frontend/.\n' + sources.map(file =>
        `\n// ---- ${file} ----\n` + normalizeText(fs.readFileSync(path.join(root, file), 'utf8'))).join('\n');
    writeIfChanged('mahler-search-app/js/app.js', bundle);
    writeIfChanged('mahler-search-app/js/score_metadata.js', fs.readFileSync(path.join(root, 'frontend/score-metadata.js'), 'utf8'));
    const versions = {};
    for (const dir of ['js', 'css']) {
        for (const name of fs.readdirSync(path.join(root, 'mahler-search-app', dir))) {
            if (!/\.(js|css)$/.test(name)) continue;
            const relative = `${dir}/${name}`;
            versions[relative] = sha256(normalizeText(fs.readFileSync(path.join(root, 'mahler-search-app', relative), 'utf8'))).slice(0, 12);
        }
    }
    const pages = ['index.html', 'privacy.html', 'license.html', ...fs.readdirSync(path.join(root, 'mahler-search-app'))
        .filter(name => name.endsWith('.html') && (options.includeDictionary || name !== 'dic.html') && !name.endsWith('_test.html'))
        .map(name => 'mahler-search-app/' + name)];
    for (const page of pages) {
        const html = languages.decorateHtml(fs.readFileSync(path.join(root, page), 'utf8'), { language: 'ja', englishEnabled, file: page, targetAliases });
        writeIfChanged(page, html.replace(/((?:src|href)=["'])(?:mahler-search-app\/)?((?:js|css)\/[^"'?]+)(?:\?v=[^"']*)?(["'])/g,
            (match, before, asset, quote) => versions[asset] ? `${before}${page.startsWith('mahler-search-app/') ? '' : 'mahler-search-app/'}${asset}?v=${versions[asset]}${quote}` : match));
    }
    return versions;
}
if (require.main === module) build();
module.exports = { build };
