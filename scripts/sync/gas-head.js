// Read-only checks for the editor HEAD. Published syncInfo alone cannot detect
// editor-only modules or edits. Never treat an unavailable check as approval.
const fs = require('fs');
const os = require('os');
const path = require('path');
const { root, run, sha256, normalizeText, gasSourceFingerprint } = require('./core');
const retirementPolicy = require('./retirement-policy');

function manifest(files) {
    if (!Array.isArray(files) || !files.length) throw new Error('GAS ファイル一覧を確認できません。');
    const seen = new Set();
    const result = files.map(file => {
        if (!file || typeof file.name !== 'string' || !file.name || /[\r\n\\]/.test(file.name) ||
            file.name.split('/').some(part => !part || part === '.' || part === '..') || seen.has(file.name) ||
            !['SERVER_JS', 'HTML', 'JSON'].includes(file.type) || typeof file.source !== 'string') {
            throw new Error('GAS ファイル一覧が不正または重複しています。');
        }
        seen.add(file.name);
        return { name: file.name, type: file.type, hash: sha256(normalizeText(file.source)) };
    }).sort((a, b) => a.name.localeCompare(b.name));
    if (!result.some(file => file.name === 'appsscript' && file.type === 'JSON')) throw new Error('GAS manifest がありません。');
    return result;
}
const digest = files => sha256(JSON.stringify(files));
const same = (a, b) => !!a && !!b && a.type === b.type && a.hash === b.hash;

function isGeneratedBuild(file) {
    return !!file && file.name === 'sync_build' && file.type === 'SERVER_JS' && typeof file.source === 'string' &&
        /^\/\/ Generated by sync-data\.\nconst SYNC_SOURCE_HASH = '[a-f0-9]{64}';\n?$/.test(normalizeText(file.source));
}
function compare(local, head, published, generatedBuildUpdate = false, retirementContext = null) {
    const approvedRetirements = retirementPolicy.approvedFiles(local, head, published, retirementContext);
    const l = new Map(local.map(file => [file.name, file]));
    const h = new Map(head.map(file => [file.name, file]));
    const p = new Map(published.map(file => [file.name, file]));
    // Only the exact reviewed retirement manifest can subtract files; unknown or edited files still block.
    const missing = head.filter(file => !l.has(file.name)).filter(file => !approvedRetirements.has(file.name)).map(file => file.name);
    const conflicts = head.filter(file => l.has(file.name) && !same(file, l.get(file.name)) && !same(file, p.get(file.name)) &&
        !(generatedBuildUpdate && file.name === 'sync_build' && file.type === 'SERVER_JS' && l.get(file.name).type === 'SERVER_JS')).map(file => file.name);
    const removed = published.filter(file => !h.has(file.name) && l.has(file.name)).map(file => file.name);
    return { missing, conflicts, removed };
}
function assertSafe(local, head, published, generatedBuildUpdate = false, retirementContext = null) {
    const difference = compare(local, head, published, generatedBuildUpdate, retirementContext);
    const parts = [];
    if (difference.missing.length) parts.push('同期元にないHEADファイル: ' + difference.missing.join(', '));
    if (difference.conflicts.length) parts.push('HEADの未統合変更: ' + difference.conflicts.join(', '));
    if (difference.removed.length) parts.push('HEADで削除されたファイル: ' + difference.removed.join(', '));
    if (parts.length) throw new Error('GAS 編集版との統合が未完了です。commit・push・GAS更新を停止しました。' + parts.join(' / '));
    return difference;
}

function localSnapshot(options = {}) {
    const directory = options.root || root;
    let configText, config;
    try {
        configText = fs.readFileSync(path.join(directory, '.clasp.json'), 'utf8');
        config = JSON.parse(configText);
    } catch (_) { throw new Error('GAS 同期設定を読み取れません。送信対象を確認してください。'); }
    if (!config || typeof config !== 'object') throw new Error('GAS 同期設定が不正です。');
    if (typeof config.scriptId !== 'string' || !/^[A-Za-z0-9_-]+$/.test(config.scriptId) || config.rootDir !== 'src' ||
        ['scriptExtensions', 'htmlExtensions', 'jsonExtensions'].some(key => config[key] !== undefined)) {
        throw new Error('GAS 同期設定が確認済みの構成と異なります。送信対象を再確認してください。');
    }
    const contentDir = fs.realpathSync(path.join(directory, config.rootDir));
    // Ask the installed clasp for its actual selection, including .claspignore.
    // Do not duplicate its glob implementation or print command output on error.
    let status;
    try {
        const output = (options.status || (() => run('clasp', ['status', '--json'], {
            cwd: directory, shell: process.platform === 'win32', timeout: 60000,
            env: { ...process.env, CI: 'true', NO_UPDATE_NOTIFIER: '1' }, redactError: true
        })))();
        status = JSON.parse(output);
    } catch (error) {
        // Preserve the fail-closed guard without exposing clasp output or credentials.
        const statusCode = /^clasp failed \((-?\d+)\):/.exec(String(error.message || ''));
        const reason = error.code === 'ETIMEDOUT' ? 'コマンドの60秒タイムアウト' :
            error.code === 'ENOENT' ? 'claspコマンドが見つかりません' :
            error instanceof SyntaxError ? 'clasp応答のJSON解析失敗' :
            statusCode ? 'clasp終了コード '+statusCode[1] : 'claspコマンド実行失敗';
        throw new Error('clasp の送信対象を確認できません。更新せず停止しました。('+reason+')');
    }
    if (!Array.isArray(status.filesToPush)) throw new Error('clasp の送信対象一覧が不正です。');
    const files = status.filesToPush.map(file => {
        if (typeof file !== 'string') throw new Error('clasp の送信パスが不正です。');
        const requested = path.resolve(directory, file);
        const absolute = fs.realpathSync(requested);
        const canonical = value => process.platform === 'win32' ? value.toLowerCase() : value;
        if (canonical(requested) !== canonical(absolute)) throw new Error('GAS 同期元のリンク先を送信対象にできません。');
        const relative = path.relative(contentDir, absolute);
        if (!relative || relative.startsWith('..' + path.sep) || relative === '..' || path.isAbsolute(relative)) throw new Error('GAS 同期元の外にあるファイルです。');
        const extension = path.extname(relative).toLowerCase();
        const type = { '.js': 'SERVER_JS', '.gs': 'SERVER_JS', '.html': 'HTML', '.json': 'JSON' }[extension];
        if (!type || (type === 'JSON' && relative !== 'appsscript.json')) throw new Error('GAS 送信形式を確認できません。');
        return { name: relative.slice(0, -extension.length).split(path.sep).join('/'), type, source: fs.readFileSync(absolute, 'utf8') };
    });
    const retirementFile = path.join(directory, 'scripts/sync/english-retirement-20261020.json');
    const retirementText = fs.existsSync(retirementFile) ? fs.readFileSync(retirementFile, 'utf8') : '';
    const retirement = retirementText ? JSON.parse(retirementText) : null;
    const ignoreFile = path.join(directory, '.claspignore');
    const build = files.find(file => file.name === 'sync_build');
    const expectedBuild = "// Generated by sync-data.\nconst SYNC_SOURCE_HASH = '" + gasSourceFingerprint(directory) + "';\n";
    return { scriptId: config.scriptId, configHash: sha256(configText + '\n' + (fs.existsSync(ignoreFile) ? fs.readFileSync(ignoreFile, 'utf8') : '') + '\n' + retirementText), retirement,
        files: manifest(files), buildVerified: isGeneratedBuild(build) && normalizeText(build.source) === expectedBuild };
}

async function readRemote(settings, scriptId, options = {}) {
    const fetchFn = options.fetch || fetch;
    const match = String(settings.GAS_DEPLOY_URL || '').match(/^https:\/\/script\.google\.com\/macros\/s\/([A-Za-z0-9_-]+)\/exec$/);
    if (!match) throw new Error('固定 GAS_DEPLOY_URL を確認できません。');
    const authPath = fs.existsSync(path.join(root, '.clasprc.json')) ? path.join(root, '.clasprc.json') : path.join(os.homedir(), '.clasprc.json');
    let credentials;
    try { credentials = options.credentials || JSON.parse(fs.readFileSync(authPath, 'utf8')).tokens.default; }
    catch (_) { throw new Error('既存の clasp 認証を読み取れません。'); }
    if (!credentials) throw new Error('既存の clasp 認証がありません。');
    async function json(url, init) {
        try {
            const response = await fetchFn(url, { ...init, redirect: 'error', signal: AbortSignal.timeout(25000) });
            if (!response.ok) throw new Error();
            return await response.json();
        } catch (_) { throw new Error('GAS 編集版の読み取りに失敗しました。認証・接続を確認してください。更新は行いません。'); }
    }
    let token = credentials.access_token;
    if (!token || Number(credentials.expiry_date) <= Date.now() + 120000 || !Number.isFinite(Number(credentials.expiry_date))) {
        if (![credentials.client_id, credentials.client_secret, credentials.refresh_token].every(v => typeof v === 'string' && v)) throw new Error('既存の clasp 認証を更新できません。');
        const renewed = await json('https://oauth2.googleapis.com/token', {
            method: 'POST', headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
            body: new URLSearchParams({ client_id: credentials.client_id, client_secret: credentials.client_secret, refresh_token: credentials.refresh_token, grant_type: 'refresh_token' })
        });
        if (typeof renewed.access_token !== 'string' || !renewed.access_token) throw new Error('clasp 認証の更新結果が不正です。');
        token = renewed.access_token;
    }
    const get = suffix => json('https://script.googleapis.com/v1/projects/' + encodeURIComponent(scriptId) + suffix, { method: 'GET', headers: { Authorization: 'Bearer ' + token } });
    const [content, deployment] = await Promise.all([get('/content'), get('/deployments/' + encodeURIComponent(match[1]))]);
    const config = deployment.deploymentConfig;
    if (deployment.deploymentId !== match[1] || !config || config.scriptId !== scriptId || !Number.isSafeInteger(config.versionNumber) || config.versionNumber < 1) throw new Error('固定公開版の対象・版番号を確認できません。');
    const published = await get('/content?versionNumber=' + config.versionNumber);
    return { files: manifest(content.files), published: manifest(published.files), version: config.versionNumber, deploymentHash: sha256(match[1]),
        buildOnly: isGeneratedBuild(content.files.find(file => file.name === 'sync_build')),
        publishedBuildOnly: isGeneratedBuild(published.files.find(file => file.name === 'sync_build')) };
}

async function preflight(settings, options = {}) {
    const local = (options.local || localSnapshot)();
    const remote = await (options.remote || readRemote)(settings, local.scriptId);
    // A generated marker is reproducible, not an independently editable module.
    // Only its hash value may differ: reject extra code and stale local markers.
    const generatedBuildUpdate = local.buildVerified === true && remote.buildOnly === true && remote.publishedBuildOnly === true;
    assertSafe(local.files, remote.files, remote.published, generatedBuildUpdate, local.retirement ? { approval: local.retirement, scriptId: local.scriptId, version: remote.version } : null);
    return { settings: { GAS_DEPLOY_URL: settings.GAS_DEPLOY_URL }, local, remote, generatedBuildUpdate };
}
async function assertUnchanged(ticket, options = {}) {
    if (!ticket || !ticket.local || !ticket.remote) throw new Error('GAS 編集版の事前確認がありません。');
    const local = (options.local || localSnapshot)();
    if (local.scriptId !== ticket.local.scriptId || local.configHash !== ticket.local.configHash || digest(local.files) !== digest(ticket.local.files)) throw new Error('確認後にGAS同期元が変わりました。更新せず停止しました。');
    const remote = await (options.remote || readRemote)(ticket.settings, local.scriptId);
    if (digest(remote.files) !== digest(ticket.remote.files) || digest(remote.published) !== digest(ticket.remote.published) || remote.version !== ticket.remote.version || remote.deploymentHash !== ticket.remote.deploymentHash) throw new Error('確認後にGAS編集版または固定公開版が変わりました。更新せず停止しました。');
}
async function verifyUpload(ticket, options = {}) {
    const local = (options.local || localSnapshot)();
    if (local.scriptId !== ticket.local.scriptId || local.configHash !== ticket.local.configHash || digest(local.files) !== digest(ticket.local.files)) throw new Error('GAS送信中に同期元が変わりました。公開更新を停止しました。');
    const remote = await (options.remote || readRemote)(ticket.settings, local.scriptId);
    if (digest(remote.files) !== digest(ticket.local.files) || digest(remote.published) !== digest(ticket.remote.published) || remote.version !== ticket.remote.version || remote.deploymentHash !== ticket.remote.deploymentHash) throw new Error('GAS送信後の全ファイル読戻しが一致しません。再送・公開更新せず停止しました。');
}
module.exports = { manifest, isGeneratedBuild, compare, assertSafe, localSnapshot, readRemote, preflight, assertUnchanged, verifyUpload };
